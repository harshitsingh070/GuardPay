package com.guardpay.risk;

import java.math.BigDecimal;

/**
 * Immutable input for the deterministic risk engine.
 *
 * <p>Plain data — no HTTP, no JPA, no AI. A {@code null} (or non-positive)
 * {@code historicalAverage} means "insufficient history": the large-amount
 * signal is skipped while every other signal is still evaluated.
 */
public record RiskEvaluationRequest(
    BigDecimal currentAmount,
    BigDecimal historicalAverage,
    boolean activeCall,
    boolean newRecipient,
    boolean repeatedAttempts,
    boolean unknownMerchant,
    boolean unexpectedInvoice,
    boolean urgentLanguage,
    boolean suspiciousUrl,
    boolean socialEngineeringDetected,
    boolean missingContext,
    boolean recipientAmountAnomaly,
    boolean newDevice,
    boolean newGeo,
    boolean impossibleTravel,
    boolean vpnProxy,
    boolean hourlyVelocity,
    boolean dailyVelocity,
    boolean blocklistedRecipient,
    boolean knownRecipientScam,
    boolean splitPayment,
    boolean amountDeviation,
    boolean unusualPaymentHour,
    boolean recipientBehaviorDeviation,
    boolean transactionFrequencyAnomaly,
    boolean geographicBehaviorDeviation,
    boolean deviceBehaviorDeviation,
    boolean overallBehaviorDeviation,
    boolean firstHighValuePayment,
    boolean firstHighValueToRecipient,
    boolean firstPaymentToRecipientHighValue,
    boolean significantAmountDeviation,
    boolean amountExceedsHistoricalMaximum,
    boolean rapidAmountEscalation) {

  /** Backward-compatible constructor for 26-flag callers. */
  public RiskEvaluationRequest(
      BigDecimal currentAmount,
      BigDecimal historicalAverage,
      boolean activeCall,
      boolean newRecipient,
      boolean repeatedAttempts,
      boolean unknownMerchant,
      boolean unexpectedInvoice,
      boolean urgentLanguage,
      boolean suspiciousUrl,
      boolean socialEngineeringDetected,
      boolean missingContext,
      boolean recipientAmountAnomaly,
      boolean newDevice,
      boolean newGeo,
      boolean impossibleTravel,
      boolean vpnProxy,
      boolean hourlyVelocity,
      boolean dailyVelocity,
      boolean blocklistedRecipient,
      boolean knownRecipientScam,
      boolean splitPayment,
      boolean amountDeviation,
      boolean unusualPaymentHour,
      boolean recipientBehaviorDeviation,
      boolean transactionFrequencyAnomaly,
      boolean geographicBehaviorDeviation,
      boolean deviceBehaviorDeviation,
      boolean overallBehaviorDeviation) {
    this(
        currentAmount,
        historicalAverage,
        activeCall,
        newRecipient,
        repeatedAttempts,
        unknownMerchant,
        unexpectedInvoice,
        urgentLanguage,
        suspiciousUrl,
        socialEngineeringDetected,
        missingContext,
        recipientAmountAnomaly,
        newDevice,
        newGeo,
        impossibleTravel,
        vpnProxy,
        hourlyVelocity,
        dailyVelocity,
        blocklistedRecipient,
        knownRecipientScam,
        splitPayment,
        amountDeviation,
        unusualPaymentHour,
        recipientBehaviorDeviation,
        transactionFrequencyAnomaly,
        geographicBehaviorDeviation,
        deviceBehaviorDeviation,
        overallBehaviorDeviation,
        false,
        false,
        false,
        false,
        false,
        false);
  }
}
